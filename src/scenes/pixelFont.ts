export function createPixelFont(scene: Phaser.Scene) {
  const chars = Object.keys(GLYPHS).join('');
  const tex = scene.textures.createCanvas(PIXEL_FONT, CELL_W * chars.length, CELL_H)!;
  const ctx = tex.getContext();

  [...chars].forEach((ch, i) => {
    const ink: [number, number][] = [];
    GLYPHS[ch].split(' ').forEach((row, y) => {
      [...row].forEach((c, x) => c === '#' && ink.push([i * CELL_W + OUTLINE + x, OUTLINE + y]));
    });
    // Outline first (every neighbour of an ink pixel), then the ink on top.
    ctx.fillStyle = OUTLINE_COLOR;
    for (const [x, y] of ink) ctx.fillRect(x - OUTLINE, y - OUTLINE, OUTLINE * 2 + 1, OUTLINE * 2 + 1);
    ctx.fillStyle = FILL;
    for (const [x, y] of ink) ctx.fillRect(x, y, 1, 1);
  });
  tex.refresh();

  const font = Phaser.GameObjects.RetroFont.Parse(scene, {
    image: PIXEL_FONT,
    width: CELL_W,
    height: CELL_H,
    chars,
    charsPerRow: chars.length,
    'offset.x': 0,
    'offset.y': 0,
    'spacing.x': 0,
    'spacing.y': 0,
    lineSpacing: LINE_SPACING,
  });
  scene.cache.bitmapFont.add(PIXEL_FONT, font);
}
